"""Extension contracts for remaining M2/M3 adapters; Windows hotkeys live in hotkeys.py."""
from typing import Callable, Protocol


class Hotkeys(Protocol):
    def register(self, shortcut: str, callback: Callable[[], None]) -> None: ...
    def unregister(self) -> None: ...


class Selection(Protocol):
    def selected_text(self) -> str | None: ...


class Capture(Protocol):
    def capture_region(self, x: int, y: int, width: int, height: int) -> bytes: ...


class Speech(Protocol):
    def speak(self, text: str, language: str) -> None: ...
    def stop(self) -> None: ...


class Permissions(Protocol):
    def status(self, capability: str) -> str: ...
    def open_settings(self, capability: str) -> None: ...


class Tray(Protocol):
    def show(self, activate: Callable[[], None], quit_app: Callable[[], None]) -> None: ...
    def hide(self) -> None: ...
